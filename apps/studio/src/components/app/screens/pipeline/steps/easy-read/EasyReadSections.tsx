import { Sparkles } from "lucide-react"
import { useLingui } from "@lingui/react/macro"
import type { EasyReadEntry, EasyReadSectionBlock } from "@/api/client"
import { cn } from "@/lib/utils"
import { EasyReadEntryRow, type EasyReadLayout } from "./EasyReadEntryRow"
import type { EasyReadBlockKey } from "./useEasyReadEdits"
import { useSectionHeading } from "./useSectionHeading"

export interface EasyReadSectionsProps {
  blocks: readonly EasyReadSectionBlock[]
  layout: EasyReadLayout
  locked: boolean
  isEdited: (blockKey: EasyReadBlockKey, entry: EasyReadEntry) => boolean
  onUpdate: (blockKey: EasyReadBlockKey, easyReadId: string, text: string) => void
  className?: string
}

export function EasyReadSections({ blocks, layout, locked, isEdited, onUpdate, className }: EasyReadSectionsProps) {
  const { t } = useLingui()
  const heading = useSectionHeading()

  return (
    <div className={cn("flex flex-col", layout === "columns" ? "divide-y" : "gap-5", className)}>
      {blocks.map((block) => (
        <section
          key={`${block.sectionId}:${block.sectionIndex}`}
          className={cn("flex flex-col gap-3", layout === "columns" && "p-3.5")}
        >
          <header className="flex min-h-5 items-center gap-1.5">
            <Sparkles
              role="img"
              aria-label={t`Generated by AI`}
              className="size-3.5 shrink-0 text-[color-mix(in_oklab,var(--chrome-hex)_80%,black)] dark:text-[color-mix(in_oklab,var(--chrome-hex)_70%,white)]"
            />
            <h3 className="min-w-0 truncate text-[12px] font-semibold text-foreground">{heading(block)}</h3>
          </header>
          <div className={cn("flex flex-col", layout === "columns" ? "gap-3.5" : "gap-4")}>
            {block.entries.map((entry) => (
              <EasyReadEntryRow
                key={entry.easyReadId}
                block={block}
                entry={entry}
                layout={layout}
                edited={isEdited(block, entry)}
                locked={locked}
                onUpdate={onUpdate}
              />
            ))}
          </div>
        </section>
      ))}
    </div>
  )
}
